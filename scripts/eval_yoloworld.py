"""Phase 3 - YOLO-World-S zero-shot baseline.

This is the direct open-vocabulary competitor. Report section 3 defines the
headline criterion against it:

    "exceeding zero-shot YOLO-World-S mAP@0.5 by at least 5 points on three
     held-out defect categories described only by text"

so this number has to exist before any TG-FEM claim can be made.

Two prompt styles are evaluated, because the choice of wording is itself a
variable the report cares about (gap G4, ablation (d)):

    bare     the class name alone       - what a naive user types
    natural  our authored description   - prompts/defect_corpus.json

No training happens here. YOLO-World is used exactly as shipped.

Run:
    python scripts/eval_yoloworld.py
    python scripts/eval_yoloworld.py --model yolov8m-worldv2.pt
"""

import argparse
import json
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO_ROOT / "src"))

DATA = REPO_ROOT / "datasets" / "neu-det-yolo" / "neu_closed.yaml"
CORPUS = REPO_ROOT / "prompts" / "defect_corpus.json"
RESULTS = REPO_ROOT / "results"

# Dataset class order - prompts MUST be supplied in this order so that the
# model's class indices line up with the label files.
CLASSES = [
    "crazing",
    "inclusion",
    "patches",
    "pitted_surface",
    "rolled-in_scale",
    "scratches",
]


# Nonsense prompts used as a negative control. If the pipeline is wired
# correctly these must score near zero; if they score the same as the real
# descriptions, the prompts are being ignored (see write_prompt_dataset).
ABSURD = ["banana", "elephant", "skateboard", "umbrella", "giraffe", "pizza"]


def build_prompts(style):
    """Return one prompt string per class, in dataset index order."""
    if style == "absurd":
        return list(ABSURD)

    corpus = json.loads(CORPUS.read_text(encoding="utf-8"))["classes"]

    prompts = []
    for cls in CLASSES:
        entry = corpus[cls]
        if style == "bare":
            # The 'bare' tier is the class name as a human would write it.
            text = next(d["text"] for d in entry["descriptions"] if d["tier"] == "bare")
        else:
            # First 'natural' tier phrase - a short description an inspector
            # would plausibly type.
            text = next(d["text"] for d in entry["descriptions"] if d["tier"] == "natural")
        prompts.append(text)
    return prompts


def write_prompt_dataset(prompts, style):
    """Write a dataset YAML whose `names` ARE the prompts.

    Why this is necessary
    ---------------------
    `WorldValidator.__call__` overrides whatever `set_classes()` set:

        names = [...check_det_dataset(self.args.data)["names"]...]
        if list(current) != names:
            model.set_classes(names, cache_clip_model=False)

    So calling `model.set_classes(my_prompts)` then `model.val()` silently
    discards `my_prompts` and re-encodes the DATASET's class names instead.
    Verified: prompts of "banana, elephant, skateboard, umbrella, giraffe,
    pizza" scored an identical mAP@0.5 of 0.04011 to the real descriptions.

    The validator is the only thing that gets to choose the vocabulary, so we
    choose it *through* the validator - by putting the prompts in the YAML.
    Ground-truth labels match on class INDEX, never on the string, so the
    metrics stay correct as long as prompt order matches label order.

    Note the validator does `name.split("/", 1)[0]`, so a prompt must not
    contain a forward slash.
    """
    assert not any("/" in p for p in prompts), "prompts must not contain '/'"

    base = DATA.parent
    content = (
        f"# Generated by scripts/eval_yoloworld.py for prompt style '{style}'.\n"
        f"# `names` are PROMPTS, not class names - see write_prompt_dataset().\n"
        f"path: {base.as_posix()}\n"
        "train: closed_train.txt\n"
        "val: closed_val.txt\n"
        "test: closed_test.txt\n\n"
        "names:\n" + "\n".join(f"  {i}: {p}" for i, p in enumerate(prompts)) + "\n"
    )
    path = base / f"_prompts_{style}.yaml"
    path.write_text(content)
    return path


def evaluate(model_name, style, args):
    from ultralytics import YOLOWorld

    prompts = build_prompts(style)
    data_yaml = write_prompt_dataset(prompts, style)

    model = YOLOWorld(model_name)
    model.set_classes(prompts)  # kept for predict(); val() re-derives from the YAML

    metrics = model.val(
        data=str(data_yaml),
        split=args.split,
        imgsz=args.imgsz,
        batch=args.batch,
        device=args.device,
        project=str(REPO_ROOT / "runs"),
        name=f"phase3_yoloworld_{style}",
        exist_ok=True,
        plots=False,
        verbose=False,
    )

    return {
        "model": model_name,
        "prompt_style": style,
        "prompts": prompts,
        "split": args.split,
        "mAP50": round(float(metrics.box.map50), 5),
        "mAP50_95": round(float(metrics.box.map), 5),
        "precision": round(float(metrics.box.mp), 5),
        "recall": round(float(metrics.box.mr), 5),
        "per_class_AP50": {
            CLASSES[c]: round(float(metrics.box.ap50[i]), 5)
            for i, c in enumerate(metrics.box.ap_class_index)
        },
    }


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--model", default="yolov8s-worldv2.pt",
                    help="report cites YOLO-World-S; v2 is the maintained release")
    ap.add_argument("--split", default="test")
    ap.add_argument("--imgsz", type=int, default=640)
    ap.add_argument("--batch", type=int, default=16)
    ap.add_argument("--device", default="0")
    args = ap.parse_args()

    print("=" * 62)
    print(f"Phase 3 - YOLO-World zero-shot ({args.model})")
    print("=" * 62)
    print(f"split: {args.split}   NO training - model used as shipped\n")

    results = []
    for style in ("bare", "natural", "absurd"):
        print(f"--- prompt style: {style} ---")
        r = evaluate(args.model, style, args)
        results.append(r)
        for cls, p in zip(CLASSES, r["prompts"]):
            print(f"    {cls:<18} <- {p!r}")
        print(f"    mAP@0.5 = {r['mAP50']:.4f}   mAP@0.5:0.95 = {r['mAP50_95']:.4f}\n")

    # --- negative control -------------------------------------------------
    by = {r["prompt_style"]: r["mAP50"] for r in results}
    real = max(by["bare"], by["natural"])
    if abs(by["absurd"] - real) < 1e-6:
        raise SystemExit(
            "\nFAILED: nonsense prompts scored identically to real ones, so the\n"
            "prompts are being ignored. See write_prompt_dataset() - the\n"
            "WorldValidator overrides set_classes() with the data YAML names.\n"
        )
    print(f"negative control OK: absurd={by['absurd']:.4f} vs real={real:.4f}\n")

    RESULTS.mkdir(exist_ok=True)
    out = RESULTS / "phase3_yoloworld.json"
    out.write_text(json.dumps(results, indent=2))

    print("=" * 62)
    print("SUMMARY - zero-shot YOLO-World on NEU-DET")
    print("=" * 62)
    print(f"{'prompt style':<14}{'mAP@0.5':>10}{'mAP@0.5:0.95':>15}")
    for r in results:
        print(f"{r['prompt_style']:<14}{r['mAP50']:>10.4f}{r['mAP50_95']:>15.4f}")
    best = max(r["mAP50"] for r in results)
    print(f"\nBest zero-shot mAP@0.5: {best:.4f}")
    print(f"TG-FEM must exceed {best + 0.05:.4f} to satisfy the +5 point criterion.")
    print(f"\nsaved -> {out}")


if __name__ == "__main__":
    main()
